#!/usr/bin/env node
/*jshint esversion: 8 */
"use strict";

// Generates the ClojureScript namespace that pulls every CodeMirror mode and
// fold addon into the bundle.
//
// These used to be discovered by walking node_modules at runtime and loaded
// with require(). That stops working the moment CodeMirror itself is bundled:
// a mode file resolves `../../lib/codemirror` out of node_modules and registers
// against that copy, which is no longer the one the editor is using. It stops
// working again, permanently, when contextIsolation removes require from the
// window.
//
// So the set has to be static. It is still discovered rather than hand-listed —
// the set is whatever the installed CodeMirror ships, and a hand-written list
// would be wrong the first time CodeMirror is upgraded.
//
// Run by `npm run build:cljs`, before shadow-cljs.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CM = path.join(ROOT, 'deploy', 'core', 'node_modules', 'codemirror');
const OUT = path.join(ROOT, 'src-gen', 'lt', 'editor', 'codemirror_modes.cljs');

// There is no blacklist any more, and removing it is the point.
//
// This inherited lt.objs.editor/mode-blacklist, which skipped six modes that a
// bundled plugin ships its own copy of. That made sense when modes were loaded
// out of node_modules at runtime, where two copies genuinely conflict. It stops
// making sense once everything is bundled: a plugin's `load-js` runs after the
// bundle and `defineMIME` overwrites, so the plugin's copy still wins.
//
// What the list actually did was make Light Table's own highlighting depend on
// which plugins happened to be installed. With no plugins, `.js` and `.json`
// had no mode, `.ts` had none under any circumstances, and — this is the one
// that decided it — neither did `.clj`, `.cljs`, `.edn`, or Light Table's own
// `.behaviors` and `.keymap` files, because `text/x-clojure` came from the
// Clojure plugin and nowhere else.
//
// Bundling all of them costs a few hundred KB on a 3.8MB bundle. Checked by
// asking the running editor which of the 102 registered mimes CodeMirror can
// resolve, which is the only way to see this: a mime nothing defines falls back
// to the null mode, silently.

function modes() {
    const dir = path.join(CM, 'mode');
    if (!fs.existsSync(dir)) return [];
    const found = [];
    for (const name of fs.readdirSync(dir).sort()) {
        const modeDir = path.join(dir, name);
        if (!fs.statSync(modeDir).isDirectory()) continue;
        for (const file of fs.readdirSync(modeDir).sort()) {
            // test.js sits beside the modes and is not one.
            if (!file.endsWith('.js') || file.endsWith('test.js')) continue;
            found.push(`codemirror/mode/${name}/${file.replace(/\.js$/, '')}`);
        }
    }
    return found;
}

function foldAddons() {
    const dir = path.join(CM, 'addon', 'fold');
    if (!fs.existsSync(dir)) return [];
    return fs.readdirSync(dir).sort()
        .filter((f) => f.endsWith('.js'))
        .map((f) => `codemirror/addon/fold/${f.replace(/\.js$/, '')}`);
}

/**
 * The addons under addon/mode, which are not optional: several modes are
 * written against them and throw on load without them.
 *
 * `simple` defines defineSimpleMode, which dockerfile, factor, handlebars,
 * nsis, rust and wast are all built on; `overlay` and `multiplex` combine
 * modes and back another eight between them. Missing, the mode file loads and
 * calls a function that is not there, so the language does not merely look
 * plain — opening the file throws.
 *
 * Rust was doing exactly that, silently, and the mime audit that found it is
 * now `script/smoke-test.js`'s job.
 *
 * Listed rather than globbed, and emitted before the modes, because the order
 * is the point: an addon has to have registered before a mode reaches for it.
 */
function modeAddons() {
    const dir = path.join(CM, 'addon', 'mode');
    if (!fs.existsSync(dir)) return [];
    return ['simple', 'overlay', 'multiplex']
        .filter((name) => fs.existsSync(path.join(dir, `${name}.js`)))
        .map((name) => `codemirror/addon/mode/${name}`);
}

function main() {
    if (!fs.existsSync(CM)) {
        console.error(`CodeMirror is missing at ${CM}. Run npm ci in deploy/core first.`);
        process.exit(1);
    }
    const requires = [...foldAddons(), ...modeAddons(), ...modes()];
    if (requires.length === 0) {
        console.error('Found no CodeMirror modes to require, which cannot be right.');
        process.exit(1);
    }

    const body = requires.map((r) => `            ["${r}"]`).join('\n');
    const source = `(ns lt.editor.codemirror-modes
  "Every CodeMirror mode and fold addon, required so they are bundled.

  GENERATED by script/gen-codemirror-requires.js — do not edit. Regenerated on
  every build, so it follows whatever version of CodeMirror is installed.

  These were discovered by walking node_modules and loaded with require() at
  startup. That cannot survive CodeMirror being bundled — a mode required out of
  node_modules registers against the copy it finds there rather than the one the
  editor uses — and it cannot survive contextIsolation at all.

  ${requires.length} files: ${foldAddons().length} fold addons, ${modeAddons().length} mode
  addons, ${modes().length} modes."
  (:require
${body}))

;; Requiring is the whole point; each file registers itself with CodeMirror as
;; it loads. Nothing here is called.
`;
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    const previous = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
    // Only rewrite when it changed, so shadow-cljs does not recompile the
    // world on every build.
    if (previous !== source) fs.writeFileSync(OUT, source);
    console.log(`codemirror requires: ${foldAddons().length} fold addons, ${modeAddons().length} mode addons, ${modes().length} modes` +
                (previous === source ? ' (unchanged)' : ''));
}

main();
